function report(agent: string, head: string, caught: boolean, durationMs: number, digest: string) {
  return {
    version: 1,
    repo: REPOSITORY,
    fork: `~/tryouts/bench/${agent.split("-")[0]}/issue-1`,
    head: { ref: `tryout/${agent}`, sha: head },
    base: { ref: "main", sha: BASE },
    verdict: caught ? "verified" : "refuted",
    sandboxed: true,
    checks: checks(caught),
    changed: {
      tests: ["test/chunk.test.ts"],
      source: ["src/chunk.ts"],
      deleted: [],
      outOfScope: [],
    },
    durationMs,
    digest,
  } satisfies ProofReport;
}

